const dicts = { da, en };
let current = 'da';

export function setLang(code) {
  current = dicts[code] ? code : 'en';
}
export const getLang = () => current;

export function tr(key, vars) {
  let s = dicts[current][key] ?? dicts.en[key] ?? key;
  if (vars) s = s.replace(/\{(\w+)\}/g, (_, k) => (vars[k] ?? ''));
  return s;
}

